package tn.esprit.workshop.model.leith;

/**
 * Miroir JDBC de {@code candidature_agent} (zayna.sql) : {@code ecole}, {@code adresse}, etc.
 */
public class CandidatureAgent {

    private int id;
    private int userId;
    private String nom;
    private String prenom;
    private String ecole;
    private String adresse;
    private double latitude;
    private double longitude;
    private CandidatureAgentStatut statut;
    /** Affichage formaté (liste admin). */
    private String createdAt;
    private String updatedAt;

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getNom() {
        return nom;
    }

    public void setNom(String nom) {
        this.nom = nom;
    }

    public String getPrenom() {
        return prenom;
    }

    public void setPrenom(String prenom) {
        this.prenom = prenom;
    }

    public String getEcole() {
        return ecole;
    }

    public void setEcole(String ecole) {
        this.ecole = ecole;
    }

    public String getAdresse() {
        return adresse;
    }

    public void setAdresse(String adresse) {
        this.adresse = adresse;
    }

    public double getLatitude() {
        return latitude;
    }

    public void setLatitude(double latitude) {
        this.latitude = latitude;
    }

    public double getLongitude() {
        return longitude;
    }

    public void setLongitude(double longitude) {
        this.longitude = longitude;
    }

    public CandidatureAgentStatut getStatut() {
        return statut;
    }

    public void setStatut(CandidatureAgentStatut statut) {
        this.statut = statut;
    }

    public String getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(String createdAt) {
        this.createdAt = createdAt;
    }

    public String getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(String updatedAt) {
        this.updatedAt = updatedAt;
    }
}
